// ----- Lang context -----
export const LangContext = createContext({ lang: "fr", setLang: () => {}, t: translations.fr });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try { return localStorage.getItem("pips_lang") || "fr"; } catch (e) { return "fr"; }
  });
  const setLang = useCallback((l) => {
    setLangState(l);
    try { localStorage.setItem("pips_lang", l); } catch (e) {}
    document.documentElement.setAttribute("lang", l);
    document.documentElement.setAttribute("data-lang", l);
  }, []);
  useEffect(() => {
    document.documentElement.setAttribute("lang", lang);
    document.documentElement.setAttribute("data-lang", lang);
  }, [lang]);

  const value = useMemo(() => ({ lang, setLang, t: translations[lang] }), [lang, setLang]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export { translations };
